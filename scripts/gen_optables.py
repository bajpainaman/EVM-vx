#!/usr/bin/env python3
"""Generates src/evm/optables.vx from the revm source.

Reads opcode names and stack inputs/outputs from bytecode/src/opcode.rs and the
static gas table plus its per-fork overrides from interpreter/src/instructions.rs,
so the numbers come straight from the reference implementation.

Usage: python3 scripts/gen_optables.py /data/pool/src/revm > src/evm/optables.vx
"""
import re
import sys
from pathlib import Path

REVM = Path(sys.argv[1] if len(sys.argv) > 1 else '/data/pool/src/revm')
SPECS = ['FRONTIER', 'HOMESTEAD', 'TANGERINE', 'SPURIOUS_DRAGON', 'BYZANTIUM', 'PETERSBURG',
         'ISTANBUL', 'BERLIN', 'LONDON', 'MERGE', 'SHANGHAI', 'CANCUN', 'PRAGUE', 'OSAKA',
         'AMSTERDAM']

# The fork that introduced each opcode, for opcodes newer than Frontier.
ACTIVATION = {
    'DELEGATECALL': 'HOMESTEAD',
    'RETURNDATASIZE': 'BYZANTIUM', 'RETURNDATACOPY': 'BYZANTIUM', 'STATICCALL': 'BYZANTIUM',
    'REVERT': 'BYZANTIUM',
    'SHL': 'PETERSBURG', 'SHR': 'PETERSBURG', 'SAR': 'PETERSBURG', 'EXTCODEHASH': 'PETERSBURG',
    'CREATE2': 'PETERSBURG',
    'CHAINID': 'ISTANBUL', 'SELFBALANCE': 'ISTANBUL',
    'BASEFEE': 'LONDON',
    'PUSH0': 'SHANGHAI',
    'TLOAD': 'CANCUN', 'TSTORE': 'CANCUN', 'MCOPY': 'CANCUN', 'BLOBHASH': 'CANCUN',
    'BLOBBASEFEE': 'CANCUN',
    'CLZ': 'OSAKA',
    'SLOTNUM': 'AMSTERDAM', 'DUPN': 'AMSTERDAM', 'SWAPN': 'AMSTERDAM', 'EXCHANGE': 'AMSTERDAM',
}


def parse_opcodes():
    text = (REVM / 'crates/bytecode/src/opcode.rs').read_text()
    ops = {}
    for m in re.finditer(r'^\s*0x([0-9A-F]{2}) => ([A-Z0-9_]+)\s*=> stack_io\((\d+), (\d+)\)',
                         text, re.M):
        ops[m.group(2)] = (int(m.group(1), 16), int(m.group(3)), int(m.group(4)))
    return ops


def parse_gas(ops):
    text = (REVM / 'crates/interpreter/src/instructions.rs').read_text()
    consts = {}
    gas_rs = (REVM / 'crates/context/interface/src/cfg/gas.rs').read_text()
    for m in re.finditer(r'pub const ([A-Z0-9_]+): u64 = (\d+);', gas_rs):
        consts[m.group(1)] = int(m.group(2))

    def value(expr):
        expr = expr.strip().replace(' as u16', '').replace('gas::', '')
        if expr.isdigit():
            return int(expr)
        if expr in consts:
            return consts[expr]
        raise ValueError(f'cannot evaluate gas expression {expr!r}')

    base_body = text[text.index('const fn gas_table_impl'):]
    base_body = base_body[:base_body.index('\n}\n')]
    base = {}
    for m in re.finditer(r'table\[([A-Z0-9_]+) as usize\] = ([^;]+);', base_body):
        base[m.group(1)] = value(m.group(2))

    spec_body = text[text.index('pub const fn gas_table_spec'):]
    spec_body = spec_body[:spec_body.index('\n}\n')]
    overrides = []
    for blk in re.finditer(r'if spec\.is_enabled_in\(([A-Z_]+)\) \{(.*?)\n    \}', spec_body, re.S):
        spec, body = blk.group(1), blk.group(2)
        entries = []
        for m in re.finditer(r'table\[([A-Z0-9_]+) as usize\] = ([^;]+);', body):
            expr = m.group(2)
            if 'warm' in expr and spec == 'AMSTERDAM':
                entries.append((m.group(1), 200))
            else:
                entries.append((m.group(1), value(expr)))
        overrides.append((spec, entries))
    return base, overrides


def main():
    ops = parse_opcodes()
    base, overrides = parse_gas(ops)
    w = print
    w('// Generated by scripts/gen_optables.py from the revm source. Do not edit by hand.')
    w('')
    w('// Fills 256-entry tables for fork `spec`: static gas, stack inputs and outputs,')
    w('// and activation (OPA_ACTIVE, OPA_INACTIVE for a known opcode of a later fork,')
    w('// OPA_UNDEFINED for an unassigned byte).')
    w('fn fill_op_tables(spec: u64, gas: *mut u64, sin: *mut u8, sout: *mut u8, act: *mut u8) -> void {')
    for name, (byte, i, o) in sorted(ops.items(), key=lambda kv: kv[1][0]):
        g = base.get(name, 0)
        w(f'  unsafe {{ gas[{byte}u64] = {g}u64; sin[{byte}u64] = {i}u8; sout[{byte}u64] = {o}u8; }}')
        fork = ACTIVATION.get(name, 'FRONTIER')
        w(f'  if spec >= {SPECS.index(fork)}u64 {{ unsafe {{ act[{byte}u64] = 1u8; }} }}'
          f' else {{ unsafe {{ act[{byte}u64] = 2u8; }} }}')
    for spec, entries in overrides:
        w(f'  if spec >= {SPECS.index(spec)}u64 {{')
        for name, g in entries:
            w(f'    unsafe {{ gas[{ops[name][0]}u64] = {g}u64; }}')
        w('  }')
    w('}')


if __name__ == '__main__':
    main()
