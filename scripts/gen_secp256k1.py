#!/usr/bin/env python3
"""Generates src/evm/secp256k1.vx: field/scalar arithmetic, Jacobian point math
and ECDSA public-key recovery for the ecrecover precompile (0x01).

Field and scalar multiplication reuse the tested u256_mulmod. Run:
  python3 scripts/gen_secp256k1.py > src/evm/secp256k1.vx
"""

P = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEFFFFFC2F
N = 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFEBAAEDCE6AF48A03BBFD25E8CD0364141
GX = 0x79BE667EF9DCBBAC55A06295CE870B07029BFCDB2DCE28D959F2815B16F81798
GY = 0x483ADA7726A3C4655DA4FBFC0E1108A8FD17B448A68554199C47D08FFB10D4B8


def limbs(v):
    return ', '.join(f'l{i}: {(v >> (64 * i)) & ((1 << 64) - 1)}u64' for i in range(4))


def const_fn(name, v):
    return f'fn {name}() -> U256 {{ return U256 {{ {limbs(v)} }}; }}'


def main():
    w = print
    w('// Generated by scripts/gen_secp256k1.py. Do not edit by hand.')
    w('// secp256k1 ECDSA public-key recovery for the ecrecover precompile.')
    w('')
    w(const_fn('secp_p', P))
    w(const_fn('secp_n', N))
    w(const_fn('secp_gx', GX))
    w(const_fn('secp_gy', GY))
    w(const_fn('secp_p_m2', P - 2))
    w(const_fn('secp_p_sqrt_exp', (P + 1) // 4))
    w(const_fn('secp_n_m2', N - 2))
    w('''
fn fp_mul(a: U256, b: U256) -> U256 { return u256_mulmod(a, b, secp_p()); }
fn fp_add(a: U256, b: U256) -> U256 { return u256_addmod(a, b, secp_p()); }
fn fp_sub(a: U256, b: U256) -> U256 { return u256_addmod(a, u256_sub(secp_p(), b), secp_p()); }
fn fn_mul(a: U256, b: U256) -> U256 { return u256_mulmod(a, b, secp_n()); }

// a ** e mod p, square and multiply from the most significant bit.
fn fp_pow(a: U256, e: U256) -> U256 {
  let mut r: U256 = u256_one();
  let mut i: i32 = 255;
  while i >= 0 {
    r = fp_mul(r, r);
    if u256_bit(e, i) != 0u64 { r = fp_mul(r, a); }
    i = i - 1;
  }
  return r;
}

fn fn_pow(a: U256, e: U256) -> U256 {
  let mut r: U256 = u256_one();
  let mut i: i32 = 255;
  while i >= 0 {
    r = fn_mul(r, r);
    if u256_bit(e, i) != 0u64 { r = fn_mul(r, a); }
    i = i - 1;
  }
  return r;
}

fn fp_inv(a: U256) -> U256 { return fp_pow(a, secp_p_m2()); }
fn fn_inv(a: U256) -> U256 { return fn_pow(a, secp_n_m2()); }

// Jacobian point (x/z^2, y/z^3). z == 0 is the point at infinity.
struct Jac { x: U256, y: U256, z: U256 }
impl Copy for Jac {}

fn jac_inf() -> Jac { return Jac { x: u256_one(), y: u256_one(), z: u256_zero() }; }
fn jac_is_inf(p: Jac) -> bool { return u256_is_zero(p.z); }

fn fp_dbl(a: U256) -> U256 { return fp_add(a, a); }

fn jac_double(p: Jac) -> Jac {
  if u256_is_zero(p.y) || u256_is_zero(p.z) { return jac_inf(); }
  let a: U256 = fp_mul(p.x, p.x);
  let b: U256 = fp_mul(p.y, p.y);
  let cc: U256 = fp_mul(b, b);
  let xb: U256 = fp_add(p.x, b);
  let d: U256 = fp_dbl(fp_sub(fp_sub(fp_mul(xb, xb), a), cc));
  let e: U256 = fp_add(fp_dbl(a), a);
  let f: U256 = fp_mul(e, e);
  let x3: U256 = fp_sub(f, fp_dbl(d));
  let eightc: U256 = fp_dbl(fp_dbl(fp_dbl(cc)));
  let y3: U256 = fp_sub(fp_mul(e, fp_sub(d, x3)), eightc);
  let z3: U256 = fp_dbl(fp_mul(p.y, p.z));
  return Jac { x: x3, y: y3, z: z3 };
}

fn jac_add(p: Jac, q: Jac) -> Jac {
  if jac_is_inf(p) { return q; }
  if jac_is_inf(q) { return p; }
  let z1z1: U256 = fp_mul(p.z, p.z);
  let z2z2: U256 = fp_mul(q.z, q.z);
  let u1: U256 = fp_mul(p.x, z2z2);
  let u2: U256 = fp_mul(q.x, z1z1);
  let s1: U256 = fp_mul(fp_mul(p.y, q.z), z2z2);
  let s2: U256 = fp_mul(fp_mul(q.y, p.z), z1z1);
  if u256_eq(u1, u2) {
    if !u256_eq(s1, s2) { return jac_inf(); }
    return jac_double(p);
  }
  let h: U256 = fp_sub(u2, u1);
  let r: U256 = fp_sub(s2, s1);
  let hh: U256 = fp_mul(h, h);
  let hhh: U256 = fp_mul(hh, h);
  let u1hh: U256 = fp_mul(u1, hh);
  let x3: U256 = fp_sub(fp_sub(fp_mul(r, r), hhh), fp_dbl(u1hh));
  let y3: U256 = fp_sub(fp_mul(r, fp_sub(u1hh, x3)), fp_mul(s1, hhh));
  let z3: U256 = fp_mul(fp_mul(h, p.z), q.z);
  return Jac { x: x3, y: y3, z: z3 };
}

fn jac_scalar(k: U256, p: Jac) -> Jac {
  let mut r: Jac = jac_inf();
  let mut i: i32 = 255;
  while i >= 0 {
    r = jac_double(r);
    if u256_bit(k, i) != 0u64 { r = jac_add(r, p); }
    i = i - 1;
  }
  return r;
}

// Affine x and y of a non-infinity point, written to out_x and out_y.
fn jac_affine(p: Jac, out_x: *mut U256, out_y: *mut U256) -> void {
  let zi: U256 = fp_inv(p.z);
  let zi2: U256 = fp_mul(zi, zi);
  let zi3: U256 = fp_mul(zi2, zi);
  unsafe { out_x[0u64] = fp_mul(p.x, zi2); out_y[0u64] = fp_mul(p.y, zi3); }
}

// Recovers the signer address from (hash, recid 0/1, r, s). Writes 20 bytes to
// out20 and returns true, or returns false if the signature is invalid.
fn ecdsa_recover(h: U256, recid: u64, r: U256, s: U256, out20: *mut u8) -> bool {
  let n: U256 = secp_n();
  if u256_is_zero(r) || !u256_lt(r, n) { return false; }
  if u256_is_zero(s) || !u256_lt(s, n) { return false; }
  // R.x = r; y^2 = x^3 + 7.
  let x: U256 = r;
  let x3: U256 = fp_mul(fp_mul(x, x), x);
  let alpha: U256 = fp_add(x3, u256_from_u64(7u64));
  let beta: U256 = fp_pow(alpha, secp_p_sqrt_exp());
  if !u256_eq(fp_mul(beta, beta), alpha) { return false; }
  let mut y: U256 = beta;
  if (beta.l0 & 1u64) != recid { y = u256_sub(secp_p(), beta); }
  let bigr: Jac = Jac { x: x, y: y, z: u256_one() };
  // u1 = -h * r^-1 mod n, u2 = s * r^-1 mod n.
  let hn: U256 = u256_mod(h, n);
  let rinv: U256 = fn_inv(r);
  let mut neg_hn: U256 = u256_zero();
  if !u256_is_zero(hn) { neg_hn = u256_sub(n, hn); }
  let u1: U256 = fn_mul(neg_hn, rinv);
  let u2: U256 = fn_mul(s, rinv);
  let g: Jac = Jac { x: secp_gx(), y: secp_gy(), z: u256_one() };
  let q: Jac = jac_add(jac_scalar(u1, g), jac_scalar(u2, bigr));
  if jac_is_inf(q) { return false; }
  let bufx: *mut U256 = calloc_words(8u64);
  let bufy: *mut U256 = offset_mut(bufx, 4i64);
  jac_affine(q, bufx, bufy);
  let pk: *mut u8 = zalloc(64u64);
  u256_store_be(pk, unsafe { bufx[0u64] });
  let py: *mut u8 = offset_mut(pk, 32i64);
  u256_store_be(py, unsafe { bufy[0u64] });
  let hash: U256 = keccak256(pk, 64u64);
  let hbuf: *mut u8 = zalloc(32u64);
  u256_store_be(hbuf, hash);
  let addr_src: *mut u8 = offset_mut(hbuf, 12i64);
  copy_bytes(out20, addr_src, 20u64);
  mfree(pk);
  mfree(hbuf);
  let bufx_raw: *mut i8 = bufx;
  unsafe { free(bufx_raw); }
  return true;
}

// 0x01: 3000 gas flat. Input (right padded to 128): hash | v | r | s.
// v must be 27 or 28. Output is the 32-byte left-padded address, or empty.
fn pc_ecrecover(input: *mut u8, len: u64, gas_limit: u64, out: *mut PcOut) -> void {
  let none: *mut u8 = null_u8();
  if 3000u64 > gas_limit { pc_set(out, PC_OOG, gas_limit, none, 0u64); return; }
  let h: U256 = u256_load_padded(input, len, 0u64);
  let v: U256 = u256_load_padded(input, len, 32u64);
  let r: U256 = u256_load_padded(input, len, 64u64);
  let s: U256 = u256_load_padded(input, len, 96u64);
  // v is 27 or 28 exactly (the whole word).
  if v.l1 != 0u64 || v.l2 != 0u64 || v.l3 != 0u64 || (v.l0 != 27u64 && v.l0 != 28u64) {
    pc_set(out, PC_OK, 3000u64, zalloc(1u64), 0u64);
    return;
  }
  let o: *mut u8 = zalloc(32u64);
  let addr: *mut u8 = offset_mut(o, 12i64);
  if ecdsa_recover(h, v.l0 - 27u64, r, s, addr) {
    pc_set(out, PC_OK, 3000u64, o, 32u64);
  } else {
    mfree(o);
    pc_set(out, PC_OK, 3000u64, zalloc(1u64), 0u64);
  }
}''')


if __name__ == '__main__':
    main()
