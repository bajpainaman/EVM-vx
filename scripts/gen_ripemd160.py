def f(j, x, y, z):
    """Boolean function of round group j (0..4), as a Vx expression."""
    n = lambda v: f'({v} ^ M32)'
    return [
        f'({x} ^ {y} ^ {z})',
        f'(({x} & {y}) | ({n(x)} & {z}))',
        f'((({x} | {n(y)}) ^ {z}) & M32)',
        f'(({x} & {z}) | ({y} & {n(z)}))',
        f'(({x} ^ ({y} | {n(z)})) & M32)',
    ][j]


def lines_for(side):
    out = []
    r, s, k = (R1, S1, K1) if side == 'l' else (R2, S2, K2)
    a, b, c, d, e = (f'{side}{v}' for v in 'abcde')
    for t in range(80):
        j = t // 16
        fj = f(j, b, c, d) if side == 'l' else f(4 - j, b, c, d)
        out.append(f'  let {side}t{t}: u64 = (rotl32(({a} + {fj} + x{r[t]} + {k[j]}u64) & M32, {s[t]}u64) + {e}) & M32;')
        out.append(f'  {a} = {e}; {e} = {d}; {d} = rotl32({c}, 10u64); {c} = {b}; {b} = {side}t{t};')
    return out


def main():
    w = print
    w('// Generated by scripts/gen_ripemd160.py. Do not edit by hand.')
    w('// RIPEMD-160 and the 0x03 precompile. 32-bit words live in u64 values.')
    w('')
    w('fn rotl32(x: u64, n: u64) -> u64 { return ((x << n) | (x >> (32u64 - n))) & M32; }')
    w('')
    w('fn le32_at(p: *mut u8, off: u64) -> u64 {')
    w('  let mut v: u64 = 0u64;')
    w('  let mut i: u64 = 0u64;')
    w('  while i < 4u64 {')
    w('    let b: u8 = unsafe { p[off + i] };')
    w('    v = v | ((b as u64) << (i * 8u64));')
    w('    i = i + 1u64;')
    w('  }')
    w('  return v;')
    w('}')
    w('')
    w('fn ripemd_block(h: *mut u64, blk: *mut u8) -> void {')
    for i in range(16):
        w(f'  let x{i}: u64 = le32_at(blk, {4 * i}u64);')
    for side in 'lr':
        for i, v in enumerate('abcde'):
            w(f'  let mut {side}{v}: u64 = unsafe {{ h[{i}u64] }};')
    for line in lines_for('l') + lines_for('r'):
        w(line)
    w('  let h0: u64 = unsafe { h[0u64] };')
    w('  let h1: u64 = unsafe { h[1u64] };')
    w('  let h2: u64 = unsafe { h[2u64] };')
    w('  let h3: u64 = unsafe { h[3u64] };')
    w('  let h4: u64 = unsafe { h[4u64] };')
    w('  unsafe {')
    w('    h[0u64] = (h1 + lc + rd) & M32;')
    w('    h[1u64] = (h2 + ld + re) & M32;')
    w('    h[2u64] = (h3 + le + ra) & M32;')
    w('    h[3u64] = (h4 + la + rb) & M32;')
    w('    h[4u64] = (h0 + lb + rc) & M32;')
    w('  }')
    w('}')
    w('')
    w('// RIPEMD-160 of n bytes at p, written as 20 bytes to out.')
    w('fn ripemd160(p: *mut u8, n: u64, out: *mut u8) -> void {')
    w('  let hraw: *mut i8 = unsafe { calloc(5u64, 8u64) };')
    w('  let h: *mut u64 = hraw;')
    for i, v in enumerate(H0):
        w(f'  unsafe {{ h[{i}u64] = {v}u64; }}')
    w('''  let mut off: u64 = 0u64;
  while n - off >= 64u64 {
    let blk: *mut u8 = offset_mut(p, off as i64);
    ripemd_block(h, blk);
    off = off + 64u64;
  }
  let last: *mut u8 = zalloc(128u64);
  let rem: u64 = n - off;
  if rem > 0u64 {
    let tail: *mut u8 = offset_mut(p, off as i64);
    copy_bytes(last, tail, rem);
  }
  unsafe { last[rem] = 128u8; }
  let mut total: u64 = 64u64;
  if rem >= 56u64 { total = 128u64; }
  // Bit length, little endian.
  let bits: u64 = n * 8u64;
  let mut i: u64 = 0u64;
  while i < 8u64 {
    unsafe { last[total - 8u64 + i] = ((bits >> (i * 8u64)) & 255u64) as u8; }
    i = i + 1u64;
  }
  ripemd_block(h, last);
  if total == 128u64 {
    let second: *mut u8 = offset_mut(last, 64i64);
    ripemd_block(h, second);
  }
  i = 0u64;
  while i < 5u64 {
    let v: u64 = unsafe { h[i] };
    let mut j: u64 = 0u64;
    while j < 4u64 {
      unsafe { out[i * 4u64 + j] = ((v >> (j * 8u64)) & 255u64) as u8; }
      j = j + 1u64;
    }
    i = i + 1u64;
  }
  mfree(last);
  unsafe { free(hraw); }
}

// 0x03: 600 + 120 per word; the 20-byte hash is left padded to 32 bytes.
fn pc_ripemd160(input: *mut u8, len: u64, gas_limit: u64, out: *mut PcOut) -> void {
  let cost: u64 = 600u64 + 120u64 * words_of(len);
  if !pc_charge(out, cost, gas_limit) { return; }
  let o: *mut u8 = zalloc(32u64);
  let dst: *mut u8 = offset_mut(o, 12i64);
  ripemd160(input, len, dst);
  pc_set(out, PC_OK, cost, o, 32u64);
}''')


