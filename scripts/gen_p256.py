#!/usr/bin/env python3
"""Generates src/evm/pc_p256.vx: ECDSA verification over secp256r1 (P-256)
for the P256VERIFY precompile (0x100, EIP-7951), following the p256 crate's
verify_prehash. Run: python3 scripts/gen_p256.py > src/evm/pc_p256.vx
"""

P = 0xffffffff00000001000000000000000000000000ffffffffffffffffffffffff
B = 0x5ac635d8aa3a93e7b3ebbd55769886bc651d06b0cc53b0f63bce3c3e27d2604b
N = 0xffffffff00000000ffffffffffffffffbce6faada7179e84f3b9cac2fc632551
GX = 0x6b17d1f2e12c4247f8bce6e563a440f277037d812deb33a0f4a13945d898c296
GY = 0x4fe342e2fe1a7f9b8ee7eb4a7c0f9e162bce33576b315ececbb6406837bf51f5


def limbs(v):
    return ', '.join(f'l{i}: {(v >> (64 * i)) & ((1 << 64) - 1)}u64' for i in range(4))


def const_fn(name, v):
    return f'fn {name}() -> U256 {{ return U256 {{ {limbs(v)} }}; }}'


def main():
    w = print
    w('// Generated by scripts/gen_p256.py. Do not edit by hand.')
    w('// secp256r1 (P-256) ECDSA verification for P256VERIFY (0x100).')
    w('')
    for name, v in (('r1_p', P), ('r1_b', B), ('r1_n', N), ('r1_gx', GX), ('r1_gy', GY),
                    ('r1_p_m2', P - 2), ('r1_n_m2', N - 2)):
        w(const_fn(name, v))
    w('''
fn r1_mul(a: U256, b: U256) -> U256 { return u256_mulmod(a, b, r1_p()); }
fn r1_add(a: U256, b: U256) -> U256 { return u256_addmod(a, b, r1_p()); }
fn r1_sub(a: U256, b: U256) -> U256 { return u256_addmod(a, u256_sub(r1_p(), b), r1_p()); }
fn r1_dbl(a: U256) -> U256 { return r1_add(a, a); }
fn r1n_mul(a: U256, b: U256) -> U256 { return u256_mulmod(a, b, r1_n()); }

fn r1_pow(a: U256, e: U256) -> U256 {
  let mut r: U256 = u256_one();
  let mut i: i32 = 255;
  while i >= 0 {
    r = r1_mul(r, r);
    if u256_bit(e, i) != 0u64 { r = r1_mul(r, a); }
    i = i - 1;
  }
  return r;
}

fn r1n_pow(a: U256, e: U256) -> U256 {
  let mut r: U256 = u256_one();
  let mut i: i32 = 255;
  while i >= 0 {
    r = r1n_mul(r, r);
    if u256_bit(e, i) != 0u64 { r = r1n_mul(r, a); }
    i = i - 1;
  }
  return r;
}

// Jacobian point on y^2 = x^3 - 3x + b; z == 0 is infinity.
struct R1Jac { x: U256, y: U256, z: U256 }
impl Copy for R1Jac {}

fn r1_inf() -> R1Jac { return R1Jac { x: u256_one(), y: u256_one(), z: u256_zero() }; }
fn r1_is_inf(p: R1Jac) -> bool { return u256_is_zero(p.z); }

// Doubling for a = -3 (dbl-2001-b).
fn r1_double(p: R1Jac) -> R1Jac {
  if u256_is_zero(p.y) || u256_is_zero(p.z) { return r1_inf(); }
  let delta: U256 = r1_mul(p.z, p.z);
  let gamma: U256 = r1_mul(p.y, p.y);
  let beta: U256 = r1_mul(p.x, gamma);
  let t: U256 = r1_mul(r1_sub(p.x, delta), r1_add(p.x, delta));
  let alpha: U256 = r1_add(r1_dbl(t), t);
  let beta4: U256 = r1_dbl(r1_dbl(beta));
  let x3: U256 = r1_sub(r1_mul(alpha, alpha), r1_dbl(beta4));
  let yz: U256 = r1_add(p.y, p.z);
  let z3: U256 = r1_sub(r1_sub(r1_mul(yz, yz), gamma), delta);
  let g2: U256 = r1_mul(gamma, gamma);
  let g8: U256 = r1_dbl(r1_dbl(r1_dbl(g2)));
  let y3: U256 = r1_sub(r1_mul(alpha, r1_sub(beta4, x3)), g8);
  return R1Jac { x: x3, y: y3, z: z3 };
}

fn r1_addp(p: R1Jac, q: R1Jac) -> R1Jac {
  if r1_is_inf(p) { return q; }
  if r1_is_inf(q) { return p; }
  let z1z1: U256 = r1_mul(p.z, p.z);
  let z2z2: U256 = r1_mul(q.z, q.z);
  let u1: U256 = r1_mul(p.x, z2z2);
  let u2: U256 = r1_mul(q.x, z1z1);
  let s1: U256 = r1_mul(r1_mul(p.y, q.z), z2z2);
  let s2: U256 = r1_mul(r1_mul(q.y, p.z), z1z1);
  if u256_eq(u1, u2) {
    if !u256_eq(s1, s2) { return r1_inf(); }
    return r1_double(p);
  }
  let h: U256 = r1_sub(u2, u1);
  let r: U256 = r1_sub(s2, s1);
  let hh: U256 = r1_mul(h, h);
  let hhh: U256 = r1_mul(hh, h);
  let u1hh: U256 = r1_mul(u1, hh);
  let x3: U256 = r1_sub(r1_sub(r1_mul(r, r), hhh), r1_dbl(u1hh));
  let y3: U256 = r1_sub(r1_mul(r, r1_sub(u1hh, x3)), r1_mul(s1, hhh));
  let z3: U256 = r1_mul(r1_mul(h, p.z), q.z);
  return R1Jac { x: x3, y: y3, z: z3 };
}

fn r1_scalar(k: U256, p: R1Jac) -> R1Jac {
  let mut r: R1Jac = r1_inf();
  let mut i: i32 = 255;
  while i >= 0 {
    r = r1_double(r);
    if u256_bit(k, i) != 0u64 { r = r1_addp(r, p); }
    i = i - 1;
  }
  return r;
}

fn p256_verify(input: *mut u8, len: u64) -> bool {
  if len != 160u64 { return false; }
  let n: U256 = r1_n();
  let p: U256 = r1_p();
  let h: U256 = u256_load_padded(input, len, 0u64);
  let r: U256 = u256_load_padded(input, len, 32u64);
  let s: U256 = u256_load_padded(input, len, 64u64);
  let qx: U256 = u256_load_padded(input, len, 96u64);
  let qy: U256 = u256_load_padded(input, len, 128u64);
  if u256_is_zero(r) || !u256_lt(r, n) { return false; }
  if u256_is_zero(s) || !u256_lt(s, n) { return false; }
  if !u256_lt(qx, p) || !u256_lt(qy, p) { return false; }
  // y^2 == x^3 - 3x + b
  let lhs: U256 = r1_mul(qy, qy);
  let x3: U256 = r1_mul(r1_mul(qx, qx), qx);
  let three_x: U256 = r1_add(r1_dbl(qx), qx);
  let rhs: U256 = r1_add(r1_sub(x3, three_x), r1_b());
  if !u256_eq(lhs, rhs) { return false; }
  let e: U256 = u256_mod(h, n);
  let wv: U256 = r1n_pow(s, r1_n_m2());
  let u1: U256 = r1n_mul(e, wv);
  let u2: U256 = r1n_mul(r, wv);
  let g: R1Jac = R1Jac { x: r1_gx(), y: r1_gy(), z: u256_one() };
  let q: R1Jac = R1Jac { x: qx, y: qy, z: u256_one() };
  let pt: R1Jac = r1_addp(r1_scalar(u1, g), r1_scalar(u2, q));
  if r1_is_inf(pt) { return false; }
  let zi: U256 = r1_pow(pt.z, r1_p_m2());
  let ax: U256 = r1_mul(pt.x, r1_mul(zi, zi));
  return u256_eq(u256_mod(ax, n), r);
}

// 0x100: 6900 gas (Osaka). Output is 32 bytes ending in 1 on success, else empty.
fn pc_p256verify(input: *mut u8, len: u64, gas_limit: u64, out: *mut PcOut) -> void {
  let cost: u64 = 6900u64;
  if !pc_charge(out, cost, gas_limit) { return; }
  if p256_verify(input, len) {
    let o: *mut u8 = zalloc(32u64);
    unsafe { o[31u64] = 1u8; }
    pc_set(out, PC_OK, cost, o, 32u64);
  } else {
    pc_set(out, PC_OK, cost, zalloc(1u64), 0u64);
  }
}''')


if __name__ == '__main__':
    main()
