def rotr(x, n):
    return f'(({x} >> {n}u32) | ({x} << {32 - n}u32))'


def emit_block(w):
    """One compression, fully unrolled: state, schedule and constants stay in registers."""
    w('// Compresses the 64-byte block at blk into s.')
    w('fn sha256_block(s: ShaState, blk: *mut u8) -> ShaState {')
    for t in range(16):
        w(f'  let mut w{t}: u32 = sha_be32(blk, {4 * t}u64);')
    v = ['a', 'b', 'c', 'd', 'e', 'f', 'g', 'h']
    for n in v:
        w(f'  let mut {n}: u32 = s.{n};')
    for t in range(64):
        if t >= 16:
            x, y = f'w{(t - 15) % 16}', f'w{(t - 2) % 16}'
            s0 = f'{rotr(x, 7)} ^ {rotr(x, 18)} ^ ({x} >> 3u32)'
            s1 = f'{rotr(y, 17)} ^ {rotr(y, 19)} ^ ({y} >> 10u32)'
            w(f'  w{t % 16} = w{t % 16} + ({s0}) + w{(t - 7) % 16} + ({s1});')
        a, b, c, d, e, f, g, h = v
        big1 = f'{rotr(e, 6)} ^ {rotr(e, 11)} ^ {rotr(e, 25)}'
        big0 = f'{rotr(a, 2)} ^ {rotr(a, 13)} ^ {rotr(a, 22)}'
        w(f'  let t1_{t}: u32 = {h} + ({big1}) + ({g} ^ ({e} & ({f} ^ {g}))) + {K[t]}u32 + w{t % 16};')
        w(f'  let t2_{t}: u32 = ({big0}) + (({a} & {b}) | ({c} & ({a} | {b})));')
        w(f'  {d} = {d} + t1_{t};')
        w(f'  {h} = t1_{t} + t2_{t};')
        v = [h, a, b, c, d, e, f, g]
    sums = ', '.join(f'{n}: s.{n} + {m}' for n, m in zip('abcdefgh', v))
    w(f'  return ShaState {{ {sums} }};')
    w('}')


