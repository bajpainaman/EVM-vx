#!/usr/bin/env python3
"""Generates src/evm/keccak.vx: Keccak-256 with an unrolled Keccak-f[1600].

Vx has no fixed arrays, so the 25 lanes are locals and every step of a round
is written out. Run: python3 scripts/gen_keccak.py > src/evm/keccak.vx
"""

RC = [
    0x0000000000000001, 0x0000000000008082, 0x800000000000808A, 0x8000000080008000,
    0x000000000000808B, 0x0000000080000001, 0x8000000080008081, 0x8000000000008009,
    0x000000000000008A, 0x0000000000000088, 0x0000000080008009, 0x000000008000000A,
    0x000000008000808B, 0x800000000000008B, 0x8000000000008089, 0x8000000000008003,
    0x8000000000008002, 0x8000000000000080, 0x000000000000800A, 0x800000008000000A,
    0x8000000080008081, 0x8000000000008080, 0x0000000080000001, 0x8000000080008008,
]

# Rotation offsets r[x][y].
ROT = [
    [0, 36, 3, 41, 18],
    [1, 44, 10, 45, 2],
    [62, 6, 43, 15, 61],
    [28, 55, 25, 21, 56],
    [27, 20, 39, 8, 14],
]


def lane(x, y):
    return f'a{x}{y}'


def rotl(expr, n):
    if n == 0:
        return expr
    return f'(({expr} << {n}u64) | ({expr} >> {64 - n}u64))'


def main():
    out = []
    w = out.append
    w('// Generated by scripts/gen_keccak.py. Do not edit by hand.')
    w('// Keccak-256 as used by Ethereum (original Keccak padding, not SHA3-256).')
    w('')
    w('fn keccak_rc(i: i32) -> u64 {')
    w('  match i {')
    for i, c in enumerate(RC):
        w(f'    {i} => {{ return {c}u64; }}')
    w('    _ => { return 0u64; }')
    w('  }')
    w('}')
    w('')
    w('// Keccak-f[1600] on 25 lanes at st; lane (x, y) is st[x + 5 * y].')
    w('fn keccak_f(st: *mut u64) -> void {')
    for y in range(5):
        for x in range(5):
            w(f'  let mut {lane(x, y)}: u64 = unsafe {{ st[{x + 5 * y}] }};')
    w('  let mut round: i32 = 0;')
    w('  while round < 24 {')
